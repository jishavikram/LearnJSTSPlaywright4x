/*  -----------  Ternary Operator -------------------

The Ternary Operator is a conditional operator in JavaScript 
that allows you to write a simple if...else statement in a single line.

*/

//Ex 1:
let age = 17;

let can_I_go = age > 18 ? "Yes" : "No";
console.log(can_I_go);

// Ex 2:
let a = 50;
let b = 30;

let greater = (a > b) ? a : b;
console.log(greater);