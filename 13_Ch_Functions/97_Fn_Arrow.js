/*Arrow Function --> is a shorter way of writing a function in JavaScript.
Arrow functions use the => symbol instead of the function keyword.

Syntax:  
const functionName = (parameters) => {
    // Function body
};

*/

// Normal Fn
function greet() {
    console.log("Hello JavaScript");
}

greet();

// Same code using Arrow Fn
const greet = () => {
    console.log("Hello JavaScript");
};

greet();



