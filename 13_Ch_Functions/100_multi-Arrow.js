// Example 2: Check even or odd

const checkEvenOdd = (num) => {
    if (num % 2 === 0) {
        return "Even";
    } else {
        return "Odd";
    }
};

console.log(checkEvenOdd(10));  // Even
console.log(checkEvenOdd(7));   // Odd

